#!/usr/bin/env node
// 1. Extract Pi's <task_completion_contract> from the vendored extensions/taskmanage/extension.ts (not bundled: it
//    imports Pi-only runtime) into src/generated/contract.ts, so the Claude prompt carries the identical bytes.
// 2. Bundle src/server.ts and src/session-start.ts into self-contained dist/*.mjs (no runtime dependencies).
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export function extractContract(source) {
	const match = /"\\n(<task_completion_contract>(?:[^"\\]|\\.)*<\/task_completion_contract>)"/.exec(source);
	if (!match) throw new Error("task_completion_contract not found in vendored extensions/taskmanage/extension.ts");
	return JSON.parse(`"${match[1]}"`);
}
const contract = extractContract(readFileSync(join(root, "vendor/trebol/extensions/taskmanage/extension.ts"), "utf8"));
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/contract.ts"), `// Generated by scripts/build.mjs from vendor/trebol/extensions/taskmanage/extension.ts. Do not edit.\nexport const TASK_COMPLETION_CONTRACT = ${JSON.stringify(contract)};\n`);

for (const [entry, out = entry] of [["server"], ["session-start"], ["api-proxy"], ["trace-hook"], ["agy-hook"], ["decision-waiter", "decision-wait"]]) {
	await build({
		entryPoints: [join(root, `src/${entry}.ts`)], outfile: join(root, `dist/${out}.mjs`),
		bundle: true, platform: "node", format: "esm", target: "node20", legalComments: "none",
		banner: { js: "// Built by scripts/build.mjs from src/ and vendor/trebol/ (see vendor/MANIFEST.json). Do not edit." },
	});
}
console.log(`built dist/server.mjs, dist/session-start.mjs, dist/api-proxy.mjs, dist/trace-hook.mjs, dist/agy-hook.mjs, dist/decision-wait.mjs; contract ${contract.length} chars`);
